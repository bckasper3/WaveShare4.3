#!/usr/bin/env python3
"""Generate the UI fonts (main/ui/ui_font_*.c) and the icon header (main/ui/ui_icons.h).

The UI ships its own fonts so the device build does not depend on which Montserrat sizes are
enabled in sdkconfig. Text fonts = Montserrat Medium (ASCII + a few symbols) merged with
FontAwesome 5 icons (LVGL's built-in LV_SYMBOL_* set plus the extra icons below). The big
result digits are a digits-only font.

Needs Node.js (npx downloads lv_font_conv on first use) and the LVGL source tree (the TTF/WOFF
files live in lvgl/scripts/built_in_font; the simulator build fetches LVGL into its build dir):

    python main/ui/fonts/gen_fonts.py <lvgl>/scripts/built_in_font

Both fonts are SIL OFL / FontAwesome Free licensed (same files LVGL ships its fonts from).
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
UI_DIR = os.path.dirname(HERE)
CONV = "lv_font_conv@1.5.2"

# Text: printable ASCII + degree, plus-minus, micro, middle dot, en/em dash, bullet, ellipsis.
TEXT_RANGE = "0x20-0x7E,0xB0,0xB1,0xB5,0xB7,0x2013,0x2014,0x2022,0x2026"

# LVGL built-in symbols (LV_SYMBOL_*), copied from lvgl/scripts/built_in_font/built_in_font_gen.py
LV_SYMS = [61441, 61448, 61451, 61452, 61453, 61457, 61459, 61461, 61465, 61468, 61473, 61478,
           61479, 61480, 61502, 61507, 61512, 61515, 61516, 61517, 61521, 61522, 61523, 61524,
           61543, 61544, 61550, 61552, 61553, 61556, 61559, 61560, 61561, 61563, 61587, 61589,
           61636, 61637, 61639, 61641, 61664, 61671, 61674, 61683, 61724, 61732, 61787, 61931,
           62016, 62017, 62018, 62019, 62020, 62087, 62099, 62212, 62189, 62810, 63426, 63650]

# Extra icons (FontAwesome 5 Free code points) -> UI_ICON_<NAME> in ui_icons.h
EXTRA = {
    "USER": 0xF007, "CLOCK": 0xF017, "LOCK": 0xF023, "FLAG": 0xF024, "TAG": 0xF02B,
    "TIMES_CIRCLE": 0xF057, "CHECK_CIRCLE": 0xF058, "INFO_CIRCLE": 0xF05A,
    "EXCL_CIRCLE": 0xF06A, "CALENDAR": 0xF073, "KEY": 0xF084, "LOCK_OPEN": 0xF3C1,
    "HDD": 0xF0A0, "WRENCH": 0xF0AD, "FILTER": 0xF0B0, "FLASK": 0xF0C3, "LIST_UL": 0xF0CA,
    "LIGHTBULB": 0xF0EB, "CIRCLE": 0xF111, "DATABASE": 0xF1C0, "HISTORY": 0xF1DA,
    "SLIDERS": 0xF1DE, "PLUG": 0xF1E6, "CHART_LINE": 0xF201, "BALANCE": 0xF24E,
    "INDUSTRY": 0xF275, "THERMO": 0xF2C9, "MICROCHIP": 0xF2DB, "STOPWATCH": 0xF2F2,
    "SIGN_OUT": 0xF2F5, "SIGN_IN": 0xF2F6, "SHIELD": 0xF3ED, "TACHO": 0xF3FD, "VIAL": 0xF492,
    "USER_SHIELD": 0xF505, "USER_COG": 0xF4FE, "NETWORK": 0xF6FF, "TINT": 0xF043,
    "TH_LARGE": 0xF009, "SUN": 0xF185, "MOON": 0xF186, "ARROW_LEFT": 0xF060,
    "REDO": 0xF01E, "STETHOSCOPE": 0xF0F1, "MICROSCOPE": 0xF610, "ROUTE": 0xF4D7,
    "EXCHANGE": 0xF362, "DOT_CIRCLE": 0xF192, "CROSSHAIRS": 0xF05B, "QUESTION": 0xF059,
}

TEXT_SIZES = [14, 16, 20, 24, 32, 48]
DIGIT_SIZES = [72, 112]
DIGITS = "0123456789.,-+<> "


def run(args, out, src):
    cmd = "npx -y " + CONV + " " + " ".join(args)
    print(cmd)
    subprocess.check_call(cmd, shell=True)
    # Keep local paths out of the committed file header.
    with open(out, "r", encoding="utf-8") as f:
        text = f.read()
    text = text.replace(src + os.sep, "").replace(UI_DIR + os.sep, "")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def utf8_escape(cp):
    return "".join("\\x%02X" % b for b in chr(cp).encode("utf-8"))


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = os.path.abspath(sys.argv[1])
    mont = os.path.join(src, "Montserrat-Medium.ttf")
    fa = os.path.join(src, "FontAwesome5-Solid+Brands+Regular.woff")
    syms = ",".join(str(s) for s in sorted(set(LV_SYMS + list(EXTRA.values()))))
    common = ["--bpp 4", "--format lvgl", "--no-compress", "--no-prefilter",
              "--force-fast-kern-format", "--lv-include lvgl.h"]
    for size in TEXT_SIZES:
        out = os.path.join(UI_DIR, "ui_font_%d.c" % size)
        run(common + ["--size %d" % size, '--font "%s"' % mont, "-r " + TEXT_RANGE,
                      '--font "%s"' % fa, "-r " + syms, '-o "%s"' % out], out, src)
    for size in DIGIT_SIZES:
        out = os.path.join(UI_DIR, "ui_font_digits_%d.c" % size)
        run(common + ["--size %d" % size, '--font "%s"' % mont,
                      '--symbols "%s"' % DIGITS, '-o "%s"' % out], out, src)

    lines = ["#pragma once",
             "/* Generated by main/ui/fonts/gen_fonts.py - do not edit. Extra FontAwesome 5 icons",
             " * present in every ui_font_<size> (LVGL's LV_SYMBOL_* icons are there too). */"]
    for name, cp in sorted(EXTRA.items()):
        lines.append('#define UI_ICON_%-14s "%s"   /* U+%04X */' % (name, utf8_escape(cp), cp))
    with open(os.path.join(UI_DIR, "ui_icons.h"), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
