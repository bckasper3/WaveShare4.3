#!/usr/bin/env python3
"""Repository word check: fails if any file name or file content contains a word from the
blocklist below. Run before every commit:

    python tools/check_clean.py

Files checked: everything git would commit (tracked files plus untracked files that are not
ignored). Outside a git checkout every file is walked except build output folders.
Contents are read as bytes and searched case-insensitively, so binary files (images, fonts,
generated C arrays) are checked too. E-mail addresses are reported as well, except the
reserved example domains (example.com / .org / .net).

The blocklist is stored reversed and base64-encoded so this file does not contain the words
in plain text. Most entries match as substrings; entries in WORD_TERMS must stand alone
(between non-letters), which avoids hits inside ordinary words.
Exit code: 0 = clean, 1 = hits found.
"""
import base64
import os
import re
import subprocess
import sys

TERMS_B64 = [
    "cmVwc2Fr", "b3JlYXJlcHNhaw==", "b3JlYQ==", "bXBw", "c3VvcnJlZg==", "b3JyZWY=",
    "bGF0ZW0gcmFldw==", "bGlv", "c2lyYmVk", "b2hveg==", "cmVwc2FrY2I=", "MTQ3NQ==", "cm10",
    "MjIxc2Rh", "cmVpcnJhYw==", "OTEyYW5p", "MDIzYnN1dA==", "cW9ycmVm", "ZWthd2l0dGlr",
    "a2NlaGNvcnJlZg==", "bm9kaWVzb3A=", "b3J0Y2Vwcw==", "cmVrcmFw", "aGNldGFzbmk=",
    "c2l5bGFuYV9saW8=", "NjIgc2VsaWYgYmNw", "ZHJhb2IgeXJldHRhYg==", "ZXZpcmRfZGVyYWhz",
    "Z25pbW1hcmdvcnAgLjEx", "Z25pcmVlbmlnbmUgLjE=",
]
WORD_TERMS_B64 = ["bmVi"]

# Folders never part of the source tree (build output, downloaded components, VCS data).
SKIP_DIRS = {".git", "build", "managed_components", "__pycache__", ".vscode"}
SKIP_FILES = {"dependencies.lock"}          # generated by the ESP-IDF component manager
# Owner's decision: this drawing is published under its own name. Only this exact path is
# exempt: the file itself is not scanned, and the path text may appear in links to it.
ALLOWED_PATH = "docs/Kasper_Backpack_REV8_dimensions.pdf"
SELF = os.path.normpath(os.path.abspath(__file__))

EMAIL = re.compile(rb"[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}")
EMAIL_OK = re.compile(rb"@(?:[A-Za-z0-9-]+\.)*example\.(?:com|org|net)$", re.I)


def decode(items):
    return [base64.b64decode(t).decode("utf-8")[::-1] for t in items]


def file_list(root):
    try:
        out = subprocess.run(["git", "-C", root, "ls-files", "-z", "--cached", "--others",
                              "--exclude-standard"], capture_output=True, check=True).stdout
        files = [f for f in out.decode("utf-8").split("\0") if f]
        if files:
            return files
    except (OSError, subprocess.CalledProcessError):
        pass
    files = []
    for d, dirs, names in os.walk(root):
        dirs[:] = [x for x in dirs if x not in SKIP_DIRS]
        for n in names:
            files.append(os.path.relpath(os.path.join(d, n), root))
    return files


def main():
    root = os.path.normpath(os.path.join(os.path.dirname(SELF), ".."))
    terms = [t.lower().encode() for t in decode(TERMS_B64)]
    words = [re.compile(rb"(?<![a-z])" + re.escape(t.lower().encode()) + rb"(?![a-z])")
             for t in decode(WORD_TERMS_B64)]
    hits = 0
    files = [f for f in file_list(root) if os.path.basename(f) not in SKIP_FILES
             and not any(p in SKIP_DIRS for p in f.replace("\\", "/").split("/"))]
    for rel in sorted(files):
        path = os.path.join(root, rel)
        if os.path.normpath(os.path.abspath(path)) == SELF or not os.path.isfile(path):
            continue
        if rel.replace("\\", "/") == ALLOWED_PATH:
            continue
        name = rel.replace("\\", "/").lower().encode()
        with open(path, "rb") as f:
            data = f.read().replace(ALLOWED_PATH.encode(), b"")
        low = data.lower()
        found = []
        for t in terms:
            if t in name:
                found.append(("name", t))
            i = low.find(t)
            if i >= 0:
                found.append((low.count(b"\n", 0, i) + 1, t))
        for w in words:
            m = w.search(name)
            if m:
                found.append(("name", m.group(0)))
            m = w.search(low)
            if m:
                found.append((low.count(b"\n", 0, m.start()) + 1, m.group(0)))
        for m in EMAIL.finditer(data):
            if not EMAIL_OK.search(m.group(0)):
                found.append((data.count(b"\n", 0, m.start()) + 1, b"<e-mail address>"))
        for where, what in found:
            hits += 1
            print("%s:%s: blocked word (%d characters)%s" % (rel, where, len(what),
                  " e-mail" if what == b"<e-mail address>" else ""))
    print("check_clean: %d files checked, %d hits" % (len(files), hits))
    return 1 if hits else 0


if __name__ == "__main__":
    sys.exit(main())
